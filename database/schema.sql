-- SEKURZEN Leave Management MVP schema
-- Run after creating the database with: psql -U postgres -d sekurzen -f database/schema.sql

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE organizations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    full_name text NOT NULL,
    email text NOT NULL,
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('employee', 'manager')),
    is_admin boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, email)
);

CREATE TABLE leave_balances (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    leave_type text NOT NULL CHECK (leave_type IN ('earned', 'sick')),
    entitlement_days integer NOT NULL CHECK (entitlement_days >= 0),
    used_days integer NOT NULL DEFAULT 0 CHECK (used_days >= 0),
    UNIQUE (user_id, leave_type)
);

CREATE TABLE leave_requests (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    employee_id uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    leave_type text NOT NULL CHECK (leave_type IN ('earned', 'sick')),
    start_date date NOT NULL,
    end_date date NOT NULL,
    working_days integer NOT NULL CHECK (working_days > 0),
    reason text NOT NULL CHECK (length(trim(reason)) > 0),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    submitted_at timestamptz NOT NULL DEFAULT now(),
    decided_at timestamptz,
    decided_by uuid REFERENCES users(id) ON DELETE SET NULL,
    CHECK (end_date >= start_date)
);

-- Pending and approved requests cannot overlap for the same employee.
ALTER TABLE leave_requests
    ADD CONSTRAINT leave_requests_no_overlap
    EXCLUDE USING gist (
        employee_id WITH =,
        daterange(start_date, end_date, '[]') WITH &&
    ) WHERE (status IN ('pending', 'approved'));

CREATE TABLE organization_managers (
    organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    manager_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (organization_id, manager_id)
);

CREATE TABLE organization_holidays (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    holiday_date date NOT NULL,
    name text NOT NULL CHECK (length(trim(name)) > 0),
    created_by uuid REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, holiday_date)
);

CREATE TABLE password_reset_requests (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved', 'cancelled')),
    requested_at timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz,
    resolved_by uuid REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE notifications (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    recipient_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    request_id uuid REFERENCES leave_requests(id) ON DELETE CASCADE,
    type text NOT NULL CHECK (type IN ('submitted', 'approved', 'rejected', 'cancelled')),
    message text NOT NULL,
    read_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX one_open_password_reset_per_user
    ON password_reset_requests(user_id)
    WHERE status = 'open';

CREATE INDEX leave_requests_employee_idx ON leave_requests(employee_id, submitted_at DESC);
CREATE INDEX leave_requests_status_idx ON leave_requests(organization_id, status);
CREATE INDEX notifications_recipient_idx ON notifications(recipient_id, created_at DESC);
CREATE INDEX organization_holidays_org_date_idx ON organization_holidays(organization_id, holiday_date);

-- Seed one organization. Passwords must be generated by the API with Argon2 or bcrypt;
-- never store plain-text passwords in this database.
